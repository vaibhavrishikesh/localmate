const IDS = new Set(LANGS.map((item) => item.id));

export function isLang(value: string): value is Lang {
  return IDS.has(value as Lang);
}

export function textDir(lang: Lang) {
  return LANGS.find((item) => item.id === lang)?.dir ?? "ltr";
}

export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "en";
  const list = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const code of list) {
    const base = code.toLowerCase().split("-")[0];
    const normalized = base === "iw" ? "he" : base;
    if (isLang(normalized)) return normalized;
  }
  return "en";
}

